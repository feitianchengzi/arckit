import { beforeEach, describe, expect, it, vi } from 'vitest'
import { fireEvent, render, screen, waitFor } from '@testing-library/react'
import { AgentChatPanel } from './AgentChatPanel'
import { saveConsultationDraft, setActiveConsultation } from '@/lib/feedback/drafts'
import * as api from '@/lib/feedback/v2'
vi.mock('@/lib/feedback/v2', () => ({ getAgentCapabilities: vi.fn().mockResolvedValue({ image_understanding: false }), getStandaloneAgentConversations: vi.fn(), getStandaloneAgentConversationsPage: vi.fn(), getStandaloneAgentMessages: vi.fn(), getStandaloneAgentMessagesPage: vi.fn(), sendStandaloneAgentMessage: vi.fn(), getAgentConversations: vi.fn(), getAgentConversationMessages: vi.fn(), sendAgentMessage: vi.fn() }))
vi.mock('./MediaComposer', () => ({ MediaComposer: ({ onSend, onDraftChange, disabled }: any) => <div><input aria-label="未发送内容" disabled={disabled} onChange={(event) => onDraftChange?.(Boolean(event.target.value))} /><button disabled={disabled} onClick={() => void onSend('新问题', []).catch(() => {})}>测试发送</button></div> }))
const conv = (id: string, feedback_id = 0) => ({ id, feedback_id, project_id: 11, created_at: `2026-10-${id === 'first' ? '11' : '12'}T00:00:00Z`, updated_at: '2026-10-12T00:00:00Z' })
const message = (text: string, summary?: object) => ({ id: 1, conversation_id: 'first', feedback_id: 0, project_id: 11, sender_type: 'agent' as const, content: text, created_at: '2026-10-12T00:00:00Z', metadata: summary ? JSON.stringify({ clarification: { summary } }) : undefined })
const openHistory = async () => { fireEvent.click(screen.getByRole('button', { name: '咨询历史' })); await waitFor(() => expect(screen.queryByText('正在加载咨询历史…')).toBeNull()) }
const rows = () => screen.getAllByRole('button').filter((button) => button.hasAttribute('aria-pressed'))
beforeEach(() => {
  vi.clearAllMocks()
  const entries = new Map<string, string>()
  Object.defineProperty(window, 'localStorage', { configurable: true, value: { getItem: (key: string) => entries.get(key) ?? null, setItem: (key: string, value: string) => entries.set(key, value), removeItem: (key: string) => entries.delete(key) } })
  vi.mocked(api.getStandaloneAgentConversations).mockResolvedValue([conv('first')])
  vi.mocked(api.getStandaloneAgentConversationsPage).mockImplementation(async () => { const conversations = await api.getStandaloneAgentConversations(); return { conversations, total: conversations.length } })
  vi.mocked(api.getStandaloneAgentMessages).mockResolvedValue([message('已有咨询记录')])
  vi.mocked(api.getStandaloneAgentMessagesPage).mockImplementation(async (id) => { const messages = await api.getStandaloneAgentMessages(id); return { messages, total: messages.length } })
})
describe('consultation history continuity', () => {
  it('refreshes each opening, hides linked feedback and guides users to their feedback', async () => {
    const mine = vi.fn()
    render(<AgentChatPanel standalone onMyFeedback={mine} />)
    await screen.findByText('已有咨询记录')
    vi.mocked(api.getStandaloneAgentConversations).mockResolvedValue([conv('first'), conv('linked', 99)])
    await openHistory(); expect(screen.getByRole('dialog', { name: '咨询历史' })).toBeInTheDocument(); expect(rows()).toHaveLength(1)
    fireEvent.click(screen.getByRole('button', { name: '前往我的反馈' })); expect(mine).toHaveBeenCalledOnce()
    await openHistory(); expect(api.getStandaloneAgentConversations).toHaveBeenCalledTimes(3)
  })
  it('shows history loading, failure and retry without hiding the active conversation', async () => {
    render(<AgentChatPanel standalone />); await screen.findByText('已有咨询记录')
    let reject!: (reason: Error) => void
    vi.mocked(api.getStandaloneAgentConversations).mockImplementationOnce(() => new Promise((_, fail) => { reject = fail }))
    fireEvent.click(screen.getByRole('button', { name: '咨询历史' }))
    expect(screen.getByText('正在加载咨询历史…')).toBeInTheDocument()
    reject(new Error('服务暂时不可用，请稍后重试。'))
    expect(await screen.findByRole('alert')).toHaveTextContent('服务暂时不可用')
    expect(screen.getByText('已有咨询记录')).toBeInTheDocument()
    vi.mocked(api.getStandaloneAgentConversations).mockResolvedValue([])
    fireEvent.click(screen.getByRole('button', { name: '重试咨询历史' }))
    await screen.findByText('暂无咨询历史。开始提问后会保留在这里。')
  })
  it('asks before discarding an unsent new consultation and keeps text when canceled', async () => {
    render(<AgentChatPanel standalone />); await screen.findByText('已有咨询记录')
    fireEvent.click(screen.getByRole('button', { name: '新咨询' }))
    fireEvent.change(screen.getByLabelText('未发送内容'), { target: { value: '不要丢失' } })
    await openHistory(); fireEvent.click(rows()[0])
    expect(screen.getByRole('dialog', { name: '切换咨询前确认' })).toBeInTheDocument()
    fireEvent.click(screen.getByRole('button', { name: '继续当前咨询' }))
    expect(screen.getByLabelText('未发送内容')).toHaveValue('不要丢失')
    expect(api.getStandaloneAgentMessages).toHaveBeenCalledTimes(1)
  })
  it('clears the old summary and restores only the selected history summary after confirmation', async () => {
    const collect = vi.fn(), ready = vi.fn()
    const summary = { position: '新位置', phenomenon: '新现象', expect: '新期望' }
    render(<AgentChatPanel standalone hasUnsubmittedSummary onNeedCollect={collect} onConversationReady={ready} />)
    await screen.findByText('已有咨询记录'); collect.mockClear()
    vi.mocked(api.getStandaloneAgentConversations).mockResolvedValue([conv('first'), conv('second')])
    vi.mocked(api.getStandaloneAgentMessages).mockResolvedValue([message('第二段咨询', summary)])
    await openHistory(); fireEvent.click(rows()[1]); fireEvent.click(screen.getByRole('button', { name: '保存草稿并切换' }))
    await screen.findByText('第二段咨询')
    expect(ready).toHaveBeenLastCalledWith('second')
    expect(collect.mock.calls.map(([payload]) => payload)).toEqual([{ question: '', structured: undefined }, { question: '', structured: summary }])
  })
  it('retains current records and unsent content when loading the selected history fails', async () => {
    render(<AgentChatPanel standalone />); await screen.findByText('已有咨询记录')
    fireEvent.change(screen.getByLabelText('未发送内容'), { target: { value: '保留草稿' } })
    vi.mocked(api.getStandaloneAgentConversations).mockResolvedValue([conv('first'), conv('second')])
    await openHistory()
    vi.mocked(api.getStandaloneAgentMessages).mockRejectedValueOnce(new Error('加载暂时失败'))
    fireEvent.click(rows()[1]); fireEvent.click(screen.getByRole('button', { name: '保存草稿并切换' }))
    await screen.findByText('加载暂时失败')
    expect(screen.getByText('已有咨询记录')).toBeInTheDocument()
    expect(screen.getByLabelText('未发送内容')).toHaveValue('保留草稿')
  })
  it('disables switching while a send is in progress and keeps the current conversation on failure', async () => {
    let fail!: (error: Error) => void
    vi.mocked(api.sendStandaloneAgentMessage).mockImplementationOnce(() => new Promise((_, reject) => { fail = reject }))
    render(<AgentChatPanel standalone />); await screen.findByText('已有咨询记录')
    fireEvent.click(screen.getByRole('button', { name: '测试发送' }))
    expect(screen.getByRole('button', { name: '咨询历史' })).toBeDisabled()
    expect(screen.getByRole('button', { name: '新咨询' })).toBeDisabled()
    fail(new Error('服务暂时不可用')); await waitFor(() => expect(screen.getByRole('button', { name: '咨询历史' })).toBeEnabled())
    expect(screen.getByText('已有咨询记录')).toBeInTheDocument()
  })
  it('refresh does not replace an unsent new draft with the latest history', async () => {
    render(<AgentChatPanel standalone />); await screen.findByText('已有咨询记录')
    fireEvent.click(screen.getByRole('button', { name: '新咨询' }))
    fireEvent.change(screen.getByLabelText('未发送内容'), { target: { value: '新咨询草稿' } })
    fireEvent.click(screen.getByRole('button', { name: '刷新' }))
    await waitFor(() => expect(api.getStandaloneAgentConversations).toHaveBeenCalledTimes(2))
    expect(screen.getByLabelText('未发送内容')).toHaveValue('新咨询草稿')
    expect(screen.queryByText('已有咨询记录')).toBeNull()
  })
  it('removes a newly submitted consultation even if a stale history response still contains it', async () => {
    const { rerender } = render(<AgentChatPanel standalone />); await screen.findByText('已有咨询记录')
    rerender(<AgentChatPanel standalone submittedConversationId="first" />)
    await waitFor(() => expect(api.getStandaloneAgentConversations).toHaveBeenCalledTimes(2))
    await openHistory(); expect(rows()).toHaveLength(0)
    expect(screen.getByRole('button', { name: '测试发送' })).toBeDisabled()
    expect(screen.getByText('暂无咨询历史。开始提问后会保留在这里。')).toBeInTheDocument()
  })
  it('loads history summaries by page without reading every conversation body', async () => {
    render(<AgentChatPanel standalone />); await screen.findByText('已有咨询记录')
    vi.mocked(api.getStandaloneAgentConversationsPage).mockResolvedValueOnce({ conversations: [{ ...conv('first'), title: '第一个问题' }], total: 2 }).mockResolvedValueOnce({ conversations: [{ ...conv('second'), title: '第二个问题' }], total: 2 })
    await openHistory()
    expect(api.getStandaloneAgentMessages).toHaveBeenCalledTimes(1)
    fireEvent.click(screen.getByRole('button', { name: '加载更多咨询' }))
    await screen.findByText('第二个问题')
    expect(screen.getByText('第一个问题')).toBeInTheDocument()
    expect(api.getStandaloneAgentConversationsPage).toHaveBeenLastCalledWith(2)
    expect(api.getStandaloneAgentMessages).toHaveBeenCalledTimes(1)
  })
  it('restores customer-edited summary instead of replacing it with an older model summary', async () => {
    const edited = { position: '客户更正的位置', phenomenon: '失败', expect: '成功' }
    saveConsultationDraft('customer-a', 'first', { structured: edited, question: '客户问题' })
    setActiveConsultation('customer-a', 'first')
    const collect = vi.fn()
    render(<AgentChatPanel standalone draftScope="customer-a" onNeedCollect={collect} />)
    await screen.findByText('已有咨询记录')
    expect(collect).toHaveBeenLastCalledWith({ question: '客户问题', structured: edited })
  })
  it('offers explicit answer completion and unresolved feedback without claiming a ticket was created', async () => {
    const direct = vi.fn()
    render(<AgentChatPanel standalone onDirectFeedback={direct} />)
    await screen.findByText('已有咨询记录')
    fireEvent.click(screen.getByRole('button', { name: /^已解答$/ }))
    expect(screen.getByRole('status')).toHaveTextContent('未创建反馈卡片')
    fireEvent.click(screen.getByRole('button', { name: '仍未解决，提交反馈' }))
    expect(direct).toHaveBeenCalledOnce()
    expect(api.sendStandaloneAgentMessage).not.toHaveBeenCalled()
  })

  it('loads earlier messages only on demand and retains the selected recent messages', async () => {
    vi.mocked(api.getStandaloneAgentMessagesPage).mockResolvedValueOnce({ messages: [message('最近记录')], total: 2 }).mockResolvedValueOnce({ messages: [{ ...message('更早记录'), id: 2 }], total: 2 })
    render(<AgentChatPanel standalone />)
    await screen.findByText('最近记录')
    fireEvent.click(screen.getByRole('button', { name: '加载更早咨询记录' }))
    await screen.findByText('更早记录')
    expect(screen.getByText('最近记录')).toBeInTheDocument()
    expect(api.getStandaloneAgentMessagesPage).toHaveBeenLastCalledWith('first', 2)
  })
  it('renders only supplied verified document evidence as escaped text from history', async () => {
    vi.mocked(api.getStandaloneAgentMessages).mockResolvedValue([{ ...message('有文档依据'), metadata: JSON.stringify({ sources: [{ path: 'docs/help/export.md', start_line: 2, end_line: 4, excerpt: '<script>不是可执行内容</script>' }] }) }])
    render(<AgentChatPanel standalone />)
    await screen.findByText('有文档依据')
    fireEvent.click(screen.getByText('查看文档依据'))
    expect(screen.getByText('docs/help/export.md:2–4')).toBeInTheDocument()
    expect(screen.getByText('<script>不是可执行内容</script>')).toBeInTheDocument()
    expect(document.querySelector('script')).toBeNull()
  })

})
